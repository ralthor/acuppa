local Font = {}

function Font.write(label, x, y, z, unit, emit)
  assert(type(label) == "string" and type(emit) == "function")
  for i = 1, #label do
    local rows = assert(glyphs[label:sub(i, i)], "unsupported display glyph")
    for row = 1, 5 do
      for col = 1, 3 do
        if rows[row]:sub(col, col) == "1" then
          emit(x + ((i - 1) * 4 + col - 1) * unit,
               y - (row - 1) * unit, z, unit * 0.43)
        end
      end
    end
  end
end

return Font
